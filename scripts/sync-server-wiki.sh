#!/usr/bin/env bash

set -euo pipefail

if [ "$#" -ne 3 ]; then
	echo "usage: $0 <generated-reports-directory> <wiki-checkout> <generated-wiki-directory>" >&2
	exit 2
fi

reports_dir="$1"
wiki_dir="$2"
wiki_docs_dir="$3"
marker="<!-- generated by shulker server-docs; do not edit -->"

if [ ! -d "$reports_dir" ]; then
	echo "reports directory does not exist: $reports_dir" >&2
	exit 1
fi

if [ ! -d "$wiki_dir/.git" ]; then
	echo "Wiki checkout is not a Git repository: $wiki_dir" >&2
	exit 1
fi

if [ ! -d "$wiki_docs_dir" ]; then
	echo "generated Wiki directory does not exist: $wiki_docs_dir" >&2
	exit 1
fi

manifest="$wiki_docs_dir/wiki-pages.txt"
if [ ! -f "$manifest" ] || [ ! -s "$manifest" ]; then
	echo "Wiki page manifest does not exist" >&2
	exit 1
fi

manifest_names="$(mktemp)"
markdown_names="$(mktemp)"
comparison_names="$(mktemp)"
cleanup() {
	rm -f -- "$manifest_names" "$markdown_names" "$comparison_names"
}
trap cleanup EXIT

while IFS= read -r page_name || [ -n "$page_name" ]; do
	case "$page_name" in
	Host-*)
		echo "reserved Wiki page name in manifest" >&2
		exit 1
		;;
	esac

	if [[ ! $page_name =~ ^(_Sidebar|_Footer|[A-Za-z0-9][A-Za-z0-9-]*)[.]md$ ]]; then
		echo "invalid Wiki page name in manifest" >&2
		exit 1
	fi

	if [ ! -f "$wiki_docs_dir/$page_name" ]; then
		echo "Wiki page manifest does not match generated Markdown files" >&2
		exit 1
	fi

	printf '%s\n' "$page_name" >>"$manifest_names"
done <"$manifest"

if sort "$manifest_names" | uniq -d | grep -q .; then
	echo "duplicate Wiki page name in manifest" >&2
	exit 1
fi

sort "$manifest_names" -o "$manifest_names"
find "$wiki_docs_dir" -maxdepth 1 -type f -name '*.md' -exec basename {} \; | sort >"$markdown_names"
comm -3 "$manifest_names" "$markdown_names" >"$comparison_names"
if [ -s "$comparison_names" ]; then
	echo "Wiki page manifest does not match generated Markdown files" >&2
	exit 1
fi

assert_managed_or_absent() {
	page="$1"
	if [ ! -e "$page" ] || grep -Fqx "$marker" "$page"; then
		return
	fi

	if [ "$(basename "$page")" = "Home.md" ] &&
		[ "$(cat "$page")" = $'# Shulker infrastructure\nRepository: [Conquerix/shulker](https://github.com/Conquerix/shulker)' ]; then
		return
	fi

	if [ -e "$page" ]; then
		echo "refusing to overwrite manually maintained Wiki page: $page" >&2
		exit 1
	fi
}

while IFS= read -r page_name; do
	assert_managed_or_absent "$wiki_dir/$page_name"
done <"$manifest_names"

report_count=0
for report in "$reports_dir"/*.md; do
	if [ ! -e "$report" ]; then
		continue
	fi

	report_count=$((report_count + 1))
	host="$(basename "$report" .md)"
	assert_managed_or_absent "$wiki_dir/Host-$host.md"
done

if [ "$report_count" -eq 0 ]; then
	echo "no Markdown reports found in: $reports_dir" >&2
	exit 1
fi

# Remove only pages carrying our marker. This clears stale generated pages and
# hosts without touching unrelated or manually maintained Wiki content.
for page in "$wiki_dir"/*.md; do
	if [ -e "$page" ] && grep -Fqx "$marker" "$page"; then
		rm -f -- "$page"
	fi
done

while IFS= read -r page_name; do
	source_page="$wiki_docs_dir/$page_name"
	page="$wiki_dir/$page_name"
	page_tmp="$wiki_dir/.$page_name.tmp"
	{
		echo "$marker"
		echo
		cat "$source_page"
	} >"$page_tmp"
	mv -- "$page_tmp" "$page"
done <"$manifest_names"

for report in "$reports_dir"/*.md; do
	host="$(basename "$report" .md)"
	page="$wiki_dir/Host-$host.md"
	page_tmp="$wiki_dir/.Host-$host.md.tmp"
	{
		echo "$marker"
		echo
		echo "[← Fleet](Fleet) · [Servers](Servers) · [Services](Services) · [Operations](Operations)"
		echo
		sed "1s/^# /# Host: /" "$report"
	} >"$page_tmp"
	mv -- "$page_tmp" "$page"
done
